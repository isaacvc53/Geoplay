def get_or_create_country(db, nombre):
    datos = MUNDO[nombre]
    pais = (
        db.query(Country)
        .filter((Country.nombre == nombre) | (Country.slug == datos["slug"]))
        .first()
    )
    if pais:
        return pais
    pais = Country(
        nombre=nombre,
        slug=datos["slug"],
        capital=datos["capital"],
        continente=continente_de(datos),
    )
    db.add(pais)
    db.flush()
    return pais


def seed_pais(db, nombre, datos, verbose=True):
    pais = get_or_create_country(db, nombre)
    if db.query(Region).filter(Region.country_id == pais.id).count():
        if verbose:
            print(f"[{nombre}] ya tiene regiones, se omite")
        return 0

    for nombres in datos["regiones"]:
        region = Region(country_id=pais.id)
        db.add(region)
        db.flush()
        for n in nombres:
            db.add(RegionName(region_id=region.id, language=IDIOMA, name=n))

    if verbose:
        print(f"[{nombre}] {len(datos['regiones'])} regiones (archivo: {datos['archivo']}.js)")
    return len(datos["regiones"])


def main():
    parser = argparse.ArgumentParser(description="Seed de provincias/regiones desde data/countries/*.js")
    parser.add_argument("--paises", nargs="+", help="Solo estos países (nombre en español).")
    parser.add_argument("--dry-run", action="store_true", help="Simula, no guarda nada.")
    parser.add_argument("--silencioso", action="store_true", help="Log mínimo.")
    args = parser.parse_args()

    seleccion = {n: d for n, d in PROVINCIAS.items() if not args.paises or n in args.paises}
    if args.paises:
        for n in set(args.paises) - set(PROVINCIAS):
            print(f"Aviso: '{n}' no está en PROVINCIAS, se omite")

    db = SessionLocal()
    total = 0
    try:
        for nombre, datos in seleccion.items():
            total += seed_pais(db, nombre, datos, verbose=not args.silencioso)

        if args.dry_run:
            db.rollback()
            print(f"\nDry-run: se crearían {total} regiones. No se ha guardado nada.")
        else:
            db.commit()
            print(f"\nSeed completado: {total} regiones nuevas.")
    except Exception as e:
        db.rollback()
        print(f"Error durante el seed: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
