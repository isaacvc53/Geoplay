export function isoForCountry(country) {
  const slug = country?.country_slug;
  if (slug && ISO_BY_SLUG[slug]) return ISO_BY_SLUG[slug];
  const name = String(country?.country_name || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();
  return ISO_BY_NAME[name] || null;
}
